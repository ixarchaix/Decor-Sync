local function key(name)
    return (tostring(name or ""):lower():gsub("[^%w]", ""))
end

ns.DecorNames = {}
for _, n in ipairs(ns.DecorNameList) do ns.DecorNames[key(n)] = true end

function ns.IsDecorName(name)
    return ns.DecorNames[key(name)] == true
end
